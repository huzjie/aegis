"""nftables backend: generate nft rules from network rules."""

import ipaddress

from aegis.backend.base import Artifact, Backend
from aegis.backend.factory import register


@register
class NftablesBackend(Backend):
    name = "nftables"

    def supports(self, ir: dict) -> bool:
        return bool(ir.get("network"))

    def compile(self, ir: dict, policy: dict | None = None) -> Artifact:
        n = ir.get("network") or {}
        name = ir.get("name", "aegis")
        chain = f"aegis-{name}"
        table = "inet aegis"
        lines = [f"# nft ruleset generated by aegis (shield '{name}')", "",
                 f"add table {table}", f"add chain {table} {chain} {{ type filter hook output priority 0; policy accept; }}"]
        for cidr in n.get("deny") or []:
            if cidr == "*":
                lines.append(f"add rule {table} {chain} ip daddr != 127.0.0.0/8 drop")
            else:
                lines.append(f"add rule {table} {chain} ip daddr {cidr} drop")
        for port in n.get("ports_deny") or []:
            lines.append(f"add rule {table} {chain} tcp dport {port} drop")
            lines.append(f"add rule {table} {chain} udp dport {port} drop")
        for port in n.get("ports_allow") or []:
            lines.append(f"add rule {table} {chain} tcp dport {port} accept")
            lines.append(f"add rule {table} {chain} udp dport {port} accept")
        return Artifact(backend=self.name, kind="text", content="\n".join(lines),
                        meta={"apply": "nft -f ruleset.nft"})
