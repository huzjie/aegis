"""AppArmor backend: generate a profile text from file rules."""

from aegis.backend.base import Artifact, Backend
from aegis.backend.factory import register


@register
class AppArmorBackend(Backend):
    name = "apparmor"

    def supports(self, ir: dict) -> bool:
        return bool(ir.get("files"))

    def compile(self, ir: dict, policy: dict | None = None) -> Artifact:
        f = ir.get("files") or {}
        name = ir.get("name", "aegis-shield")
        lines = [f"# AppArmor profile generated by aegis for shield '{name}'", "",
                 f"profile aegis/{name} flags=(attach_disconnected) {{",
                 "  #include <abstractions/base>"]
        for path in f.get("deny_write") or []:
            lines.append(f"  deny w {path},")
        for path in f.get("deny_read") or []:
            lines.append(f"  deny r {path},")
        for path in f.get("allow") or []:
            lines.append(f"  {path} rw,")
        lines.append("}")
        return Artifact(backend=self.name, kind="profile",
                        content="\n".join(lines),
                        meta={"load": "apparmor_parser -r <profile>"})
