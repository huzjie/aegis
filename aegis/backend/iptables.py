"""iptables backend: legacy fallback generating iptables commands."""

from aegis.backend.base import Artifact, Backend
from aegis.backend.factory import register


@register
class IptablesBackend(Backend):
    name = "iptables"

    def supports(self, ir: dict) -> bool:
        return bool(ir.get("network"))

    def compile(self, ir: dict, policy: dict | None = None) -> Artifact:
        n = ir.get("network") or {}
        name = ir.get("name", "aegis")
        lines = [f"# iptables commands generated by aegis (shield '{name}')"]
        for cidr in n.get("deny") or []:
            if cidr == "*":
                lines.append("iptables -A OUTPUT ! -d 127.0.0.0/8 -j DROP")
            else:
                lines.append(f"iptables -A OUTPUT -d {cidr} -j DROP")
        for port in n.get("ports_deny") or []:
            lines.append(f"iptables -A OUTPUT -p tcp --dport {port} -j DROP")
            lines.append(f"iptables -A OUTPUT -p udp --dport {port} -j DROP")
        return Artifact(backend=self.name, kind="text", content="\n".join(lines),
                        meta={"apply": "run these iptables commands as root"})
