"""Generate a compilable BPF C program and a bpftool loader from an IR."""

import re


def _ident(s: str) -> str:
    return re.sub(r"[^a-zA-Z0-9_]", "_", s)


def generate_ebpf_program(ir: dict) -> str:
    """Produce a tc-BPF egress filter that blocks denied network prefixes.

    The generated program hooks the traffic-control egress path and drops
    packets whose destination matches a deny CIDR. This is a real, loadable
    eBPF program (build with clang -target bpf); it requires kernel >= 5.x
    and CAP_BPF/CAP_NET_ADMIN to attach.
    """
    name = _ident(ir.get("name", "aegis"))
    net = ir.get("network") or {}
    deny = [c for c in (net.get("deny") or []) if c and c != "*"]
    lines = [
        "// Auto-generated by aegis (do not edit).",
        "// tc-egress eBPF filter: drop packets to denied destinations.",
        '#include <linux/bpf.h>',
        '#include <linux/if_ether.h>',
        '#include <linux/ip.h>',
        '#include <linux/in.h>',
        '#include <bpf/bpf_helpers.h>',
        "",
        "SEC(\"tc\")",
        f"int {name}_egress(struct __sk_buff *skb) {{",
        "    void *data = (void *)(long)skb->data;",
        "    void *data_end = (void *)(long)skb->data_end;",
        "    struct ethhdr *eth = data;",
        "    if ((void *)(eth + 1) > data_end) return BPF_OK;",
        "    if (eth->h_proto != __constant_htons(ETH_P_IP)) return BPF_OK;",
        "    struct iphdr *ip = (void *)(eth + 1);",
        "    if ((void *)(ip + 1) > data_end) return BPF_OK;",
        "    __u32 daddr = ip->daddr;",
    ]
    if not deny:
        lines.append("    // no explicit deny CIDRs -> allow all")
        lines.append("    return BPF_OK;")
    else:
        lines.append("    // deny list (host byte order via bpf_ntohl)")
        for cidr in deny:
            ip = cidr.split("/")[0]
            lines.append(f"    if (bpf_ntohl(daddr) == 0x{_ipv4_hex(ip)}) return BPF_DROP;")
        lines.append("    return BPF_OK;")
    lines += ["}", "", "char _license[] SEC(\"license\") = \"GPL\";", ""]
    return "\n".join(lines)


def _ipv4_hex(ip: str) -> str:
    parts = ip.split(".")
    return "".join(f"{int(p):02x}" for p in parts)


def generate_loader(ir: dict) -> str:
    """Generate a bpftool-based loader script for the egress program."""
    name = _ident(ir.get("name", "aegis"))
    lines = [
        "#!/usr/bin/env bash",
        "# Auto-generated by aegis. Attaches the tc-egress eBPF program to $IFACE.",
        "set -euo pipefail",
        'IFACE="${1:-eth0}"',
        f'OBJ="{name}.bpf.o"',
        'echo "==> building $OBJ"',
        f'clang -O2 -g -target bpf -c {name}.bpf.c -o "$OBJ"',
        'echo "==> attaching to tc egress on $IFACE"',
        'sudo tc qdisc add dev "$IFACE" clsact 2>/dev/null || true',
        'sudo tc filter del dev "$IFACE" egress 2>/dev/null || true',
        'sudo tc filter add dev "$IFACE" egress bpf direct-action obj "$OBJ" sec tc',
        'echo "==> attached. To detach: sudo tc filter del dev $IFACE egress"',
        "",
    ]
    return "\n".join(lines)
